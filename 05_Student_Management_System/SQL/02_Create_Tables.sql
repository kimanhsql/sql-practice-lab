-- CREATE TABLES
-- ============================================================

USE STUDENT_DB;
GO


CREATE TABLE DEPARTMENTS
(
    DepartmentID VARCHAR(4),
    DepartmentName NVARCHAR(40) NOT NULL,
    EstablishedDate SMALLDATETIME,
    HeadTeacherID VARCHAR(4) NOT NULL,

    CONSTRAINT PK_DEPARTMENTS PRIMARY KEY(DepartmentID)
);
GO


CREATE TABLE SUBJECTS
(
    SubjectID VARCHAR(10),
    SubjectName NVARCHAR(40) NOT NULL,
    TheoryCredits TINYINT,
    PracticalCredits TINYINT,
    DepartmentID VARCHAR(4) NOT NULL,

    CONSTRAINT PK_SUBJECTS PRIMARY KEY(SubjectID),

    CONSTRAINT FK_DEPARTMENTS_SUBJECTS FOREIGN KEY(DepartmentID)
        REFERENCES DEPARTMENTS(DepartmentID)
);
GO

CREATE TABLE PREREQUISITES
(
    SubjectID VARCHAR(10),
    PrerequisiteSubjectID VARCHAR(10),

    CONSTRAINT PK_PREREQUISITES PRIMARY KEY(SubjectID, PrerequisiteSubjectID),

    CONSTRAINT FK_SUBJECTS_PREREQ FOREIGN KEY(SubjectID)
        REFERENCES SUBJECTS(SubjectID),

    CONSTRAINT FK_SUBJECTS_PREREQ_BEFORE FOREIGN KEY(PrerequisiteSubjectID)
        REFERENCES SUBJECTS(SubjectID)
);
GO

CREATE TABLE TEACHERS
(
    TeacherID VARCHAR(4),
    FullName NVARCHAR(40) NOT NULL,
    AcademicDegree NVARCHAR(10),
    AcademicTitle NVARCHAR(10),
    Gender NVARCHAR(3),
    DateOfBirth SMALLDATETIME,
    HireDate SMALLDATETIME,
    SalaryCoefficient NUMERIC(4,2),
    Salary MONEY,
    DepartmentID VARCHAR(4) NOT NULL,

    CONSTRAINT PK_TEACHERS PRIMARY KEY(TeacherID),

    CONSTRAINT FK_DEPARTMENTS_TEACHERS FOREIGN KEY(DepartmentID)
        REFERENCES DEPARTMENTS(DepartmentID)
);
GO

CREATE TABLE CLASSES
(
    ClassID VARCHAR(3),
    ClassName NVARCHAR(40) NOT NULL,
    ClassMonitorID VARCHAR(5) NOT NULL,
    ClassSize TINYINT,
    HeadTeacherID VARCHAR(4) NOT NULL,

    CONSTRAINT PK_CLASSES PRIMARY KEY(ClassID),

    CONSTRAINT FK_TEACHERS_CLASSES FOREIGN KEY(HeadTeacherID)
        REFERENCES TEACHERS(TeacherID)
);
GO

CREATE TABLE STUDENTS
(
    StudentID VARCHAR(5),
    FirstName NVARCHAR(40),
    LastName NVARCHAR(10),
    DateOfBirth SMALLDATETIME,
    Gender NVARCHAR(3),
    BirthPlace NVARCHAR(40),
    ClassID VARCHAR(3) NOT NULL,

    CONSTRAINT PK_STUDENTS PRIMARY KEY(StudentID),

    CONSTRAINT FK_CLASSES_STUDENTS FOREIGN KEY(ClassID)
        REFERENCES CLASSES(ClassID)
);
GO

CREATE TABLE TEACHING_SCHEDULE
(
    ClassID VARCHAR(3),
    SubjectID VARCHAR(10),
    TeacherID VARCHAR(4),
    Semester TINYINT,
    Year SMALLINT,
    StartDate SMALLDATETIME,
    EndDate SMALLDATETIME,

    CONSTRAINT PK_TEACHING_SCHEDULE PRIMARY KEY(ClassID, SubjectID),

    CONSTRAINT FK_CLASSES_SCHEDULE FOREIGN KEY(ClassID)
        REFERENCES CLASSES(ClassID),

    CONSTRAINT FK_SUBJECTS_SCHEDULE FOREIGN KEY(SubjectID)
        REFERENCES SUBJECTS(SubjectID),

    CONSTRAINT FK_TEACHERS_SCHEDULE FOREIGN KEY(TeacherID)
        REFERENCES TEACHERS(TeacherID)
);
GO

CREATE TABLE EXAM_RESULTS
(
    StudentID VARCHAR(5),
    SubjectID VARCHAR(10),
    AttemptNo TINYINT,
    ExamDate SMALLDATETIME,
    Score NUMERIC(4,2),
    Result VARCHAR(10),

    CONSTRAINT PK_EXAM_RESULTS PRIMARY KEY(StudentID, SubjectID, AttemptNo),

    CONSTRAINT FK_STUDENTS_EXAM FOREIGN KEY(StudentID)
        REFERENCES STUDENTS(StudentID),

    CONSTRAINT FK_SUBJECTS_EXAM FOREIGN KEY(SubjectID)
        REFERENCES SUBJECTS(SubjectID)
);
GO