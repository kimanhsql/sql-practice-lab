USE PROJECT_DB;
GO


CREATE TABLE PHONGBAN
(
    MAPHG VARCHAR(5),
    TENPHG NVARCHAR(100),
    TRGPHG VARCHAR(5),
    NGNC DATE,

    CONSTRAINT PK_PHONGBAN PRIMARY KEY(MAPHG)
);
GO


CREATE TABLE NHANVIEN
(
    MANV VARCHAR(5),
    HONV NVARCHAR(20),
    TENLOT NVARCHAR(20),
    TENNV NVARCHAR(30),
    NGSINH DATE,
    DCHI NVARCHAR(100),
    PHAI NVARCHAR(3),
    MLUONG DECIMAL(10, 2),
    MA_NQL VARCHAR(5),
    PHONG VARCHAR(5),

    CONSTRAINT PK_NHANVIEN PRIMARY KEY(MANV),

    CONSTRAINT FK_NV_PHONG
        FOREIGN KEY(PHONG)
        REFERENCES PHONGBAN(MAPHG),

    CONSTRAINT FK_NV_NQL
        FOREIGN KEY(MA_NQL)
        REFERENCES NHANVIEN(MANV),

    CONSTRAINT CHK_NV_PHAI CHECK(PHAI IN (N'Nam', N'Nữ'))
);
GO


CREATE TABLE DIADIEMPHG
(
    MAPHG VARCHAR(5),
    DIADIEM NVARCHAR(100),

    CONSTRAINT PK_DIADIEM PRIMARY KEY(MAPHG, DIADIEM)
);
GO


CREATE TABLE DIADIEMPHG
(
    MAPHG VARCHAR(5),
    DIADIEM NVARCHAR(100),

    CONSTRAINT PK_DIADIEM PRIMARY KEY(MAPHG, DIADIEM),

    CONSTRAINT FK_DDP_PB
        FOREIGN KEY(MAPHG)
        REFERENCES PHONGBAN(MAPHG)
);
GO


CREATE TABLE DEAN
(
    MADA VARCHAR(5),
    TENDA NVARCHAR(100),
    DDIEM_DA NVARCHAR(100),
    PHONG VARCHAR(5),
    NGBD_DA DATE,
    NGKT_DA DATE,

    CONSTRAINT PK_DEAN PRIMARY KEY(MADA),

    CONSTRAINT FK_DA_PHONG
        FOREIGN KEY(PHONG)
        REFERENCES PHONGBAN(MAPHG),

    CONSTRAINT CHK_DA_NGAY CHECK(NGKT_DA >= NGBD_DA)
);
GO


CREATE TABLE PHANCONG
(
    MANV VARCHAR(5),
    MADA VARCHAR(5),
    THOIGIAN INT,

    CONSTRAINT PK_PHANCONG PRIMARY KEY(MANV, MADA),

    CONSTRAINT FK_PC_NV
        FOREIGN KEY(MANV)
        REFERENCES NHANVIEN(MANV),

    CONSTRAINT FK_PC_DA
        FOREIGN KEY(MADA)
        REFERENCES DEAN(MADA),

    CONSTRAINT CHK_PC_THOIGIAN CHECK(THOIGIAN > 0)
);
GO


CREATE TABLE THANNHAN
(
    MANV VARCHAR(5),
    MATN VARCHAR(5),
    HOTN NVARCHAR(20),
    TENTN NVARCHAR(40),
    PHAI NVARCHAR(3),
    NGAYSINH DATE,
    QUANHE NVARCHAR(20),

    CONSTRAINT PK_THANNHAN PRIMARY KEY(MANV, MATN),

    CONSTRAINT FK_TN_NV
        FOREIGN KEY(MANV)
        REFERENCES NHANVIEN(MANV),

    CONSTRAINT CHK_TN_PHAI CHECK(PHAI IN (N'Nam', N'Nữ'))
);
GO